"""Generate the note's derived TeX inputs from committed StaleLine files (never typed numbers).

Writes, next to this script:
  phantom.tex       phantom_* keys from origin/check-phantom:results/robustness_phantom/ (commit recorded)
  extra.tex         spec_*, run_*, laggard_*, count_* keys read from committed code and result files on main
  prereg_table.tex  Appendix A pre-registration timeline, parsed from docs/holdout_run_disclosure.md
  posthoc_table.tex Appendix B table, parsed from results/posthoc/SUMMARY.md

Every key is written with a "% source" comment. Usage: python3 make_tables.py
"""
from __future__ import annotations

import csv
import io
import json
import os
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path(os.environ["STALELINE_REPO"]).resolve() if os.environ.get("STALELINE_REPO") else (
    HERE.parent / "staleline" if (HERE.parent / "staleline" / ".git").exists() else HERE.parents[1])
PHANTOM_REF = "origin/check-phantom"


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], check=True, capture_output=True, text=True).stdout


def show(ref: str, path: str) -> str:
    return git("show", f"{ref}:{path}")


def tex_escape(s: str) -> str:
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    s = s.replace(">=", r"$\geq$").replace("<=", r"$\leq$").replace(" > ", r" $>$ ").replace(" < ", r" $<$ ")
    s = s.replace("--", "-{}-")
    return s


def neg(x: str) -> str:
    """Typeset a leading minus as a real minus sign, inside math."""
    return x


class Keys:
    def __init__(self) -> None:
        self.rows: list[tuple[str, str, str]] = []

    def add(self, key: str, value, source: str) -> None:
        self.rows.append((key, str(value), source))

    def write(self, path: Path, header: str) -> None:
        lines = [f"% GENERATED by make_tables.py; do not edit. {header}",
                 r"\providecommand{\defval}[2]{\expandafter\def\csname val@#1\endcsname{#2}}"]
        for k, v, src in self.rows:
            lines.append(f"\\defval{{{k}}}{{{v}}}  % {src}")
        path.write_text("\n".join(lines) + "\n")


def f(x: float, d: int) -> str:
    return f"{x:.{d}f}"


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}\\%"


def thousands(n) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def sci(x: float) -> str:
    m, e = f"{x:.2e}".split("e")
    return f"${m}\\times 10^{{{int(e)}}}$"


