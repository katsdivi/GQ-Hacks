def part_h(sl: Path) -> None:
    """h0: Polymarket US snapshot gaps per game window, snapshot age at 1 s laggard fills, results split by age,
    lead-test lags split by window p90 gap. Our data only, no network."""
    sys.path.insert(0, str(ROOT / "scripts"))
    import final_test_run as F
    machines, cands, maps = ctx(sl)
    res = sl / "results" / "holdout"
    pg = pd.read_csv(res / "lead_Polymarket US_per_game.csv")
    q = pg[pg["qualifying"].fillna(False).astype(bool)]
    lt = pd.read_csv(res / "laggard_trades.csv")
    f1 = lt[(lt.venue == "polymarket_us") & (lt.latency_s == 1.0) & lt["filled"].astype(bool)].copy()
    gaps, ages = [], []
    for r in q.itertuples():
        m, i = machines[r.machine], inst(cands, maps, r.game_id)
        lo, end = int(r.window_start_ns), int(r.window_end_ns)
        rows = F.rows_with_size(m, "polymarket_us", i["polymarket_us"], lo - 3600 * NS, end + 3600 * NS)
        b = L.book(rows, "polymarket_us")
        ts = b["ts"].to_numpy("int64")
        w = ts[(ts >= lo) & (ts < end)]
        d = np.diff(w) / NS
        gaps.append({"game_id": r.game_id, "machine": r.machine, "n_snapshots": len(w),
                     "gap_median_s": float(np.median(d)) if len(d) else np.nan,
                     "gap_p90_s": float(np.quantile(d, 0.9)) if len(d) else np.nan,
                     "gap_p99_s": float(np.quantile(d, 0.99)) if len(d) else np.nan,
                     "gap_max_s": float(d.max()) if len(d) else np.nan,
                     "share_gaps_gt_2s": float((d > 2).mean()) if len(d) else np.nan, "lag_s": r.lag_s})
        for x in f1[f1.game_id == r.game_id].itertuples():
            je = np.searchsorted(ts, x.entry_fill_ns, side="right") - 1
            jx = np.searchsorted(ts, x.exit_fill_ns, side="right") - 1
            ages.append({"idx": x.Index, "entry_snapshot_age_s": (x.entry_fill_ns - ts[je]) / NS if je >= 0 else np.nan,
                         "exit_snapshot_age_s": (x.exit_fill_ns - ts[jx]) / NS if jx >= 0 else np.nan})
    G = pd.DataFrame(gaps)
    G.to_csv(OUT / "h0_snapshot_gaps_per_game.csv", index=False)
    A = pd.DataFrame(ages).set_index("idx")
    f1 = f1.join(A)
    f1[["game_id", "entry_fill_ns", "exit_fill_ns", "entry_snapshot_age_s", "exit_snapshot_age_s",
        "edge_cents_per_contract", "pnl_cents"]].to_csv(OUT / "h0_fill_snapshot_ages.csv", index=False)

    def q_(x):
        x = x.dropna()
        return {"n": len(x), "median": x.median(), "p90": x.quantile(0.9), "p99": x.quantile(0.99), "max": x.max(),
                "share_gt_1.5s": float((x > 1.5).mean()), "share_gt_5s": float((x > 5).mean())}
    age_dist = pd.DataFrame({"entry": q_(f1["entry_snapshot_age_s"]), "exit": q_(f1["exit_snapshot_age_s"])}).T

    def stats(d):
        g = d.groupby("game_id")
        lo, hi = L.game_bootstrap_ci(g["edge_cents_per_contract"].sum().to_numpy(), g.size().to_numpy())
        top5 = g["pnl_cents"].sum().nlargest(5).index
        return {"n_fills": len(d), "n_games": g.ngroups, "mean_net_c_per_contract": d["edge_cents_per_contract"].mean(),
                "ci_lo": lo, "ci_hi": hi, "share_games_pnl_positive": float((g["pnl_cents"].sum() > 0).mean()),
                "mean_excl_top5_games": d[~d.game_id.isin(top5)]["edge_cents_per_contract"].mean()}
    fresh = f1[(f1.entry_snapshot_age_s <= 1.5) & (f1.exit_snapshot_age_s <= 1.5)]
    split = pd.DataFrame([{"sample": "all 1 s fills (run)", **stats(f1)},
                          {"sample": "both snapshot ages <= 1.5 s (EXPLORATORY)", **stats(fresh)},
                          {"sample": "rest (EXPLORATORY)", **stats(f1.drop(fresh.index))}])
    split.to_csv(OUT / "h0_laggard_by_snapshot_age.csv", index=False)
    G["p90_le_1.5"] = G["gap_p90_s"] <= 1.5
    lead = G.groupby("p90_le_1.5").agg(n_games=("lag_s", "size"), median_lag_s=("lag_s", "median"),
                                       share_positive=("lag_s", lambda x: float((x > 0).mean()))).reset_index()
    lead.to_csv(OUT / "h0_lead_by_window_gap.csv", index=False)
    allg = np.concatenate([[]])
    (OUT / "h0_note.txt").write_text(H0_NOTE + "\n")
    pd.set_option("display.width", 250)
    print(H0_NOTE)
    print("per-game window gap stats, distribution over the", len(G), "qualifying Polymarket US games:")
    print(G[["n_snapshots", "gap_median_s", "gap_p90_s", "gap_p99_s", "gap_max_s", "share_gaps_gt_2s"]].describe(percentiles=[.1, .5, .9]).T.to_string())
    print("snapshot age at 1 s fills:"); print(age_dist.to_string())
    print(split.to_string(index=False))
    print("lead test, Polymarket US, by window p90 snapshot gap <= 1.5 s (report only; decision unchanged):")
    print(lead.to_string(index=False))


