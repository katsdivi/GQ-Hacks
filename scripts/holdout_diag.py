def part_d(sl: Path) -> None:
    import b_orientation_check as BO  # noqa: E402  (scripts/, rule fixed in 0014b1e)
    import run_strategy_b as RSB
    import strategy_b as B
    res, hr = sl / "results" / "holdout", sl / "data" / "holdout_raw"
    t = pd.read_parquet(res / "strategy_b_trades.parquet")
    chk = BO.run(t, hr / "kalshi", hr / "polymarket", "{}.parquet", "{}.parquet")
    e = chk[chk["evaluable"].astype(bool)]
    big = e[e["median_abs_diff"] > 0.10].sort_values("median_abs_diff", ascending=False)
    ev = pd.read_csv(hr / "events.csv").set_index("game_id")
    pm = pd.read_csv(hr / "pm_map.csv").set_index("game_id")
    rows = []
    for g in big.itertuples():
        kt, pt = pd.read_parquet(hr / "kalshi" / f"{g.game_id}.parquet"), pd.read_parquet(hr / "polymarket" / f"{g.game_id}.parquet")
        ko_g = pd.Timestamp(ev.loc[g.game_id, "espn_kickoff"]).value // NS
        sel = t[(t.game_id == g.game_id) & (t.k == 0.05) & (t.m == 10) & (t["T"] == 300)]
        dec = np.sort(np.concatenate([sel.entry_dec_ns.to_numpy("int64"), sel.exit_dec_ns.to_numpy("int64")])) // NS - 1
        lo_g, hi_g = int(min(dec.min(), ko_g - 1800)), int(max(dec.max(), ko_g + 7200))
        kp, _ = B.venue_grid(kt, "kalshi", lo_g, hi_g)
        pp, _ = B.venue_grid(pt, "polymarket", lo_g, hi_g)
        row = {"game_id": g.game_id, "league": ev.loc[g.game_id, "league"], "pm_slug": pm.loc[g.game_id, "pm_slug"],
               "pm_outcomes (away, home)": f"{pm.loc[g.game_id, 'pm_away']} / {pm.loc[g.game_id, 'pm_home']}",
               "kalshi (away, home)": f"{ev.loc[g.game_id, 'k_away']} / {ev.loc[g.game_id, 'k_home']}",
               "pm_flipped": bool(pm.loc[g.game_id, "pm_flipped"]), "median_abs_diff": g.median_abs_diff,
               "n_decisions": g.n_decisions}
        mm = 0
        for name, off in (("ko-30", -1800), ("ko", 0), ("ko+60", 3600), ("ko+120", 7200)):
            k, p = kp[ko_g + off - lo_g], pp[ko_g + off - lo_g]
            row[f"K_{name}"], row[f"PM_{name}"] = round(float(k), 4), round(float(p), 4)
            if k == k and p == p and abs(k - p) > 0.20 and abs(k - (1 - p)) < 0.05:
                mm += 1
        ages = {}
        for v, tr in (("kalshi", kt), ("polymarket", pt)):
            ts = np.sort(tr.loc[tr["kind"] == "trade", "ts"].to_numpy("int64")) // NS if "kind" in tr else np.sort(tr["ts"].to_numpy("int64")) // NS
            j = np.searchsorted(ts, dec, side="right") - 1
            a = np.where(j >= 0, dec - ts[np.clip(j, 0, None)], np.nan)
            ages[v] = float(np.nanmedian(a)) if len(a) else np.nan
        row.update(median_last_trade_age_s_kalshi=ages["kalshi"], median_last_trade_age_s_pm=ages["polymarket"])
        if mm >= 3:
            row["class"] = "mismatch"
        elif max(ages.values()) > 120:
            row["class"] = f"stale venue ({max(ages, key=ages.get)})"
        else:
            row["class"] = "real disagreement"
        rows.append(row)
    d = pd.DataFrame(rows)
    d.to_csv(OUT / "d_b_big_diff_games.csv", index=False)
    f_all = t[(t.k == 0.05) & (t.m == 10) & (t["T"] == 300)]
    n_games = int(pd.read_csv(res / "strategy_b_summary.csv")["games"].iloc[0])
    s_all = RSB.summarize(f_all, n_games).assign(sample="all (reproduces strategy_b_summary.csv)")
    s_ex = RSB.summarize(f_all[~f_all.game_id.isin(d.game_id)], n_games - len(d)).assign(
        sample=f"excluding the {len(d)} games with median |K - PM| > 0.10 (EXPLORATORY)")
    s = pd.concat([s_all, s_ex], ignore_index=True)
    s.to_csv(OUT / "d_b_excluding.csv", index=False)
    (OUT / "d_rule.txt").write_text(D_RULE + "\n")
    pd.set_option("display.width", 250)
    print(D_RULE)
    print(d.to_string(index=False))
    print(s[["sample", "games", "n_trades", "edge_webull_cents", "edge_webull_ci_lo", "edge_webull_ci_hi",
             "edge_direct_cents", "edge_direct_ci_lo", "edge_direct_ci_hi"]].to_string(index=False))


