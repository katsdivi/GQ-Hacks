def part_x(sl: Path) -> None:
    """g1 additions (post-step on g's saved trades, nothing recomputed): per latency point and venue, per-game
    net P&L stats, per-game Sharpe (mean / sd of per-game net P&L, NOT annualized), concentration."""
    t = pd.read_parquet(OUT / "g_laggard_trades.parquet")
    f = t[t["filled"].astype(bool)]
    rows = []
    for (v, lat), d in f.groupby(["venue", "latency_s"]):
        g = d.groupby("game_id").agg(pnl=("pnl_cents", "sum"), n=("pnl_cents", "size"),
                                     contracts=("qty", "sum"))
        g["pnl"] = g["pnl"] / 100                                    # dollars
        top5 = g.nlargest(5, "pnl").index
        rest = d[~d["game_id"].isin(top5)]
        sd = g["pnl"].std(ddof=1)
        rows.append({"venue": v, "latency_s": lat, "n_games_with_trade": len(g), "n_trades": len(d),
                     "per_game_pnl_mean_usd": g["pnl"].mean(), "per_game_pnl_median_usd": g["pnl"].median(),
                     "per_game_pnl_sd_usd": sd, "share_games_pnl_positive": float((g["pnl"] > 0).mean()),
                     "per_game_sharpe_not_annualized": g["pnl"].mean() / sd if sd > 0 else np.nan,
                     "net_c_per_contract_excl_top5_games": float(rest["edge_cents_per_contract"].mean()),
                     "n_trades_excl_top5": len(rest)})
    import report_book as RB
    days = pd.date_range("2026-08-06", "2026-10-04", freq="D")     # OOS season days (numbers.json OOS.season_*)
    sh = []
    for (v, lat), d in f.groupby(["venue", "latency_s"]):
        # day = exit fill time (ET), as report_book's books close on the exit (report_book.py:61)
        b = pd.DataFrame({"day": pd.to_datetime(d["exit_fill_ns"], unit="ns", utc=True).dt.tz_convert("America/New_York").dt.date,
                          "pnl_webull": d["pnl_cents"] / 100, "contracts": d["qty"], "notional": d["qty"] * d["entry_px"]})
        pnl = RB.daily(b, days)
        sh.append({"venue": v, "latency_s": lat, "sharpe_x365_season_days": RB.metrics(pnl, 1.0, b)["sharpe"],
                   "days_with_trades": int((pnl != 0).sum())})
    c = pd.read_csv(OUT / "g_latency_curves.csv").drop(columns=["sharpe_x365_season_days", "days_with_trades"], errors="ignore")
    c = c.merge(pd.DataFrame(sh), on=["venue", "latency_s"], how="left")
    c.to_csv(OUT / "g_latency_curves.csv", index=False)
    out = c.merge(pd.DataFrame(rows), on=["venue", "latency_s", "n_trades"], how="left")
    out["sharpe_x365_season_days"] = out["sharpe_x365_season_days"].map(lambda x: f"{x:.3f} (degenerate, one day, not reported)")
    out.to_csv(OUT / "g1_latency_table.csv", index=False)
    pd.set_option("display.width", 300)
    print(out[["venue", "latency_s", "n_trades", "n_games_with_trade", "edge_cents_mean", "edge_ci_low", "edge_ci_high",
               "per_game_pnl_mean_usd", "per_game_pnl_median_usd", "per_game_pnl_sd_usd", "share_games_pnl_positive",
               "per_game_sharpe_not_annualized", "net_c_per_contract_excl_top5_games", "sharpe_x365_season_days"]].to_string(index=False))


