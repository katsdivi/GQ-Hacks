def corr_profile(tk, to, other, exc, max_lag=X.MAX_LAG_S) -> dict:
    """Same lines as xcorr_lead.game_lag_mid, returning the whole correlation profile."""
    gx, gy = X.mid_grid(X.mid_snapshots(tk, "kalshi")), X.mid_grid(X.mid_snapshots(to, other))
    if gx.empty or gy.empty:
        return {}
    lo, hi = max(gx.index.min(), gy.index.min()), min(gx.index.max(), gy.index.max())
    if hi - lo + 1 < 2 * max_lag + 2:
        return {}
    idx = np.arange(lo, hi + 1, dtype="int64")
    rx, ry = X.mid_changes(gx, exc).reindex(idx), X.mid_changes(gy, exc).reindex(idx)
    corr = {lag: float(rx.corr(ry.shift(-lag))) for lag in range(-max_lag, max_lag + 1)}
    n_pairs = {lag: int((rx.notna() & ry.shift(-lag).notna()).sum()) for lag in (-1, 0, 1)}
    nz = {lag: int(((rx.abs() > 1e-12) & (ry.shift(-lag).abs() > 1e-12)).sum()) for lag in (-1, 0, 1)}
    return {"corr": corr, "pairs": n_pairs, "both_moved": nz}


def summarize_profile(p: dict) -> dict:
    c = {k: (v if v == v else -np.inf) for k, v in p["corr"].items()}
    lag = max(c, key=c.get)                         # the run's choice: first maximal key in order -15 .. +15
    best = c[lag]
    ties = sorted(k for k, v in c.items() if np.isfinite(best) and abs(v - best) <= 1e-12)
    rest = sorted((v for k, v in c.items() if k not in ties), reverse=True)
    neg = max((v for k, v in c.items() if k < 0), default=-np.inf)
    return {"lag_s": float(lag) if np.isfinite(best) else np.nan, "corr_best": best, "n_tied_lags": len(ties),
            "tied_lags": " ".join(map(str, ties)), "margin_to_next": best - rest[0] if rest else np.nan,
            "corr_lag0": c.get(0), "corr_best_negative": neg, "n_nan_lags": sum(1 for v in p["corr"].values() if v != v),
            "pairs_lag0": p["pairs"][0], "both_moved_lag0": p["both_moved"][0], "both_moved_lag-1": p["both_moved"][-1],
            "both_moved_lag+1": p["both_moved"][1]}


def part_a(sl: Path) -> None:
    machines, cands, maps = ctx(sl)
    res = sl / "results" / "holdout"
    rows = []
    for test, (other, _) in H.TESTS.items():
        pg = pd.read_csv(res / f"lead_{test}_per_game.csv")
        q = pg[pg["qualifying"].fillna(False).astype(bool)]
        for r in q.itertuples():
            m, i = machines[r.machine], inst(cands, maps, r.game_id)
            lo, end = int(r.window_start_ns), int(r.window_end_ns)
            tk = m.rows("kalshi", i["kalshi"], lo, end)
            to = m.rows(other, i[other], lo, end)
            tk, to = tk[(tk.ts >= lo) & (tk.ts < end)], to[(to.ts >= lo) & (to.ts < end)]
            p = corr_profile(tk, to, other, [(int(r.excl_lo_g), int(r.excl_hi_g))])
            s = summarize_profile(p) if p else {"lag_s": np.nan}
            rows.append({"test": test, "kind": "real", "game": r.game_id, "recorded_lag_s": r.lag_s, **s,
                         **{f"c{k:+d}": v for k, v in (p.get("corr") or {}).items()}})
        pl = pd.read_csv(res / f"lead_{test}_placebo.csv")
        for r in pl.itertuples():
            a = q[q.game_id == r.game_a].iloc[0]
            m = machines[r.machine]
            lo, end = int(a.window_start_ns), int(a.window_end_ns)
            tk = m.rows("kalshi", inst(cands, maps, r.game_a)["kalshi"], lo, end - 1)
            to = m.rows(other, inst(cands, maps, r.game_b)[other], lo, end - 1)
            p = corr_profile(tk, to, other, [(int(a.excl_lo_g), int(a.excl_hi_g))]) if len(tk) and len(to) else {}
            s = summarize_profile(p) if p else {"lag_s": np.nan}
            rows.append({"test": test, "kind": "placebo", "game": f"{r.game_a}|{r.game_b}", "recorded_lag_s": r.lag_s,
                         **s, **{f"c{k:+d}": v for k, v in (p.get("corr") or {}).items()}})
        print(f"{test}: done", flush=True)
    d = pd.DataFrame(rows)
    d.to_csv(OUT / "a_corr_profiles.csv", index=False)
    match = (d["lag_s"].fillna(-99) == d["recorded_lag_s"].fillna(-99))
    lags = range(-15, 16)
    dist = []
    for (t, k), x in d.groupby(["test", "kind"]):
        vc = x["recorded_lag_s"].dropna().astype(int).value_counts()
        dist.append({"test": t, "kind": k, "n": int(x["recorded_lag_s"].notna().sum()),
                     **{f"{l:+d}": int(vc.get(l, 0)) for l in lags}})
    pd.DataFrame(dist).to_csv(OUT / "a_lag_distribution.csv", index=False)
    summ = []
    for (t, k), x in d.groupby(["test", "kind"]):
        x = x[x["recorded_lag_s"].notna()]
        summ.append({"test": t, "kind": k, "n": len(x), "recomputed_lag_matches_recorded": int(match[x.index].sum()),
                     "games_with_tied_max": int((x["n_tied_lags"] > 1).sum()),
                     "games_lag0": int((x["recorded_lag_s"] == 0).sum()),
                     "median_margin_to_next": float(x["margin_to_next"].median()),
                     "median_corr_lag0": float(x["corr_lag0"].median()),
                     "median_corr_best_negative": float(x["corr_best_negative"].median()),
                     "median_both_moved_lag0": float(x["both_moved_lag0"].median()),
                     "median_both_moved_lag-1": float(x["both_moved_lag-1"].median()),
                     "median_both_moved_lag+1": float(x["both_moved_lag+1"].median())})
    pd.DataFrame(summ).to_csv(OUT / "a_summary.csv", index=False)
    print(pd.DataFrame(dist).to_string(index=False))
    print(pd.DataFrame(summ).T.to_string())


